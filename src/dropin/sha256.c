/* SHA-256 (FIPS 180-4), our own: used by the drop-in to recognise WINRACE.EXE and its
 * patch sites, by the launcher to check WINRACE.EXE before starting it, and by the DOS
 * patcher (16-bit too: inputs up to 512 MB). */
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include "sha256.h"

