/* Big Red Racing DOS patch (Phase 3b): finer angles for drawing, in integers.
 * The stutter hunt's fix (docs/reports/stutter-hunt.md, H2), as in src/dropin/angles.c.
 *
 * The renderer builds every rotation from a 1,024-entry sine table (rotation_matrix,
 * 0x59E20), so the picture can only turn in steps of 64 angle units (0.35 degrees); and
 * the follow camera's pitch and yaw come from an arctangent that also returns multiples
 * of 64. During the race draw only:
 *  - brr_rotation_fine replaces rotation_matrix. It repeats the original's arithmetic
 *    step by step, but reads the table at the full 16-bit angle, interpolating between
 *    neighbouring entries. When the low 6 bits are zero the interpolation adds exactly
 *    nothing, so for every multiple of 64 the result is the original's, bit for bit
 *    (the logging build's --prove compares all 1,024^3 combinations).
 *  - brr_fine_camera_angles recomputes the follow camera's pitch and yaw (and the
 *    trackside cameras' in the demo) from the same inputs as camera_aim, without
 *    rounding: an integer arctangent from a table of our own (atan_table.h, generated by
 *    the build) and an integer square root. */
#include "brrdos.h"
#include "atan_table.h"   /* ATAN_TABLE[257]: atan(i / 256) in 1/16 angle units */

#define SINE_TABLE   (game_sine_table)
#define COSINE_TABLE (game_sine_table + 256)
#define FRACTION     16   /* camera angles are worked out in 1/16 of the game's units */

static s32 table_at(const s16 *table, u32 angle)
{
    u32 i = (angle >> 6) & 1023, f = angle & 63;
    s32 a = table[i], b = table[(i + 1) & 1023];
    return a + sar((b - a) * (s32)f, 6);
}

#define S(x) table_at(SINE_TABLE, (u32)(x) & 0xFFFFu)
#define K(x) table_at(COSINE_TABLE, (u32)(x) & 0xFFFFu)

/* rotation_matrix with fine angles: pitch, yaw, roll as the original receives them in
 * EAX, EBX, ECX (only the low 16 bits count); m is the 3x3 matrix at EBP; regs gets the
 * values the original leaves in EAX, EBX, ECX, EDX. Products stay within 32 bits: table
 * values are at most 32767 in size, so (s1 + s2) * sa is at most 65534 x 32767 < 2^31. */
void brr_rotation_fine(struct rot_args *a)
{
    u32 pitch = a->pitch, yaw = a->yaw, roll = a->roll;
    s32 *m = a->m;
    s32 sa = S(pitch), s1, s2, t1, t2;
    game_rot_a = (pitch >> 5) & 0x7FE;
    game_rot_b = (yaw >> 5) & 0x7FE;
    game_rot_c = (roll >> 5) & 0x7FE;
    game_rot_sin_a = sa;

    s1 = S(yaw + roll);
    s2 = S(yaw - roll);
    t1 = sar((s1 + s2) * sa, 15);
    t2 = sar((s1 - s2) * sa, 15);
    m[6] = sar(t2 - s1 - s2, 1);
    m[1] = sar(-t1 + s1 - s2, 1);

    s1 = K(yaw + roll);
    s2 = K(yaw - roll);
    t1 = sar((s1 + s2) * sa, 15);
    t2 = sar((s2 - s1) * sa, 15);
    m[7] = -sar(t1 + s2 - s1, 1);
    m[0] = sar(t2 + s1 + s2, 1);

    m[3] = -sar(S(pitch + roll) - S(pitch - roll), 1);
    m[4] = sar(K(pitch + roll) + K(pitch - roll), 1);

    m[2] = sar(S(pitch + yaw) - S(pitch - yaw), 1);
    m[5] = sa;
    m[8] = sar(K(pitch - yaw) + K(pitch + yaw), 1);

    a->regs[0] = (u32)m[2];
    a->regs[1] = (u32)sa;
    a->regs[2] = 0x7FE;
    a->regs[3] = (u32)S(pitch - yaw);
}

/* ---- arctangent and square root in integers ---- */

static u32 magnitude(s32 v) { return v < 0 ? (u32)-v : (u32)v; }

/* atan2(y, x) in 1/16 of the game's angle units (65,536 units a turn), the same
 * convention as the game's atan2_units: y is the "sine" side, x the "cosine" side.
 * Both must be under 65,536 in size. */
static s32 atan2_fine(s32 y, s32 x)
{
    u32 ax = magnitude(x), ay = magnitude(y), r, i, f;
    s32 angle;
    int steep = ay > ax;
    if (!ax && !ay)
        return 0;
    r = steep ? (ax << 16) / ay : (ay << 16) / ax;   /* tangent in the first octant, 16.16 */
    i = r >> 8;
    f = r & 255;
    angle = (s32)ATAN_TABLE[i];
    if (i < 256)
        angle += (s32)(((ATAN_TABLE[i + 1] - ATAN_TABLE[i]) * f) >> 8);
    if (steep)
        angle = 16384 * FRACTION - angle;
    if (x < 0)
        angle = 32768 * FRACTION - angle;
    return y < 0 ? -angle : angle;
}

static u32 square_root(u32 v)   /* floor(sqrt(v)) */
{
    u32 r = 0, bit = 1UL << 30;
    while (bit > v)
        bit >>= 2;
    while (bit) {
        if (v >= r + bit) {
            v -= r + bit;
            r = (r >> 1) + bit;
        } else {
            r >>= 1;
        }
        bit >>= 2;
    }
    return r;
}

static s16 to_angle(s32 fine)   /* 1/16 units to whole units, to the nearest */
{
    return (s16)(u16)(u32)sar(fine + FRACTION / 2, 4);
}

static s16 clamp_pitch(s32 pitch)
{
    return (s16)(pitch > 0x2000 ? 0x2000 : pitch < -0x2000 ? -0x2000 : pitch);
}

/* After camera_update for a view, during the race draw: the follow camera's (mode 4)
 * pitch and yaw, unrounded, into the drawn camera angles. camera_mode4 aims the camera
 * at the truck with camera_aim (the arctangents above, rounded to 64 units), then turns
 * it part of the way toward the truck's heading (camera_look_ahead): by a quarter of the
 * difference (folded back beyond a right angle) times speed (at most 4,000) / 4,000.
 * Both are repeated here without the rounding. Mode 3 (the demo's trackside cameras)
 * aims the same way with a height per vehicle type and no look-ahead. */
void brr_fine_camera_angles(const u8 *record, s16 *angles)
{
    const u8 *vehicle;
    s32 offset, look_pitch, look_yaw, speed, heading, dx, dy, dz, pitch, yaw, diff, d;
    s32 biggest, fine_pitch, fine_yaw;
    int mode = *(const u16 *)record, shift = 0;
    if (!(mode == 4 && record[0x45] != 0xFF) && mode != 3)
        return;   /* mode 4 held by its dead band, or another mode */
    vehicle = *(const u8 *const *)(record + 0x40);
    if (!vehicle)
        return;
    if (mode == 4) {
        offset = *(const s32 *)(record + 0x54);
        if (record[0x44] & 0x7F)
            offset += (*(const s32 *)(record + 0x48) - offset) * (s32)(record[0x44] & 0x7F) / 100;
        offset = -offset;
    } else {
        offset = (s16)(u16)(game_camera_heights[(u32)(*(const s32 *)(vehicle + 0x24) >> 16) * 2] >> 16);
    }
    dx = *(const s32 *)vehicle - *(const s32 *)(record + 0x02);
    dz = *(const s32 *)(vehicle + 8) - *(const s32 *)(record + 0x0A);
    dy = *(const s32 *)(vehicle + 4) + offset - *(const s32 *)(record + 0x06);
    /* scale all three alike so the largest is 2^14..2^15: the ratios are what count */
    biggest = (s32)magnitude(dx);
    if ((s32)magnitude(dz) > biggest) biggest = (s32)magnitude(dz);
    if ((s32)magnitude(dy) > biggest) biggest = (s32)magnitude(dy);
    if (!biggest)
        return;
    while (biggest >= 0x8000) { biggest >>= 1; shift--; }
    while (biggest < 0x4000) { biggest <<= 1; shift++; }
    if (shift < 0) {
        dx = sar(dx, -shift); dy = sar(dy, -shift); dz = sar(dz, -shift);
    } else {
        dx <<= shift; dy <<= shift; dz <<= shift;
    }
    pitch = atan2_fine(dy, (s32)square_root((u32)(dx * dx) + (u32)(dz * dz)));
    yaw = atan2_fine(dx, dz);
    speed = *(const s32 *)(vehicle + 0x230);
    if (speed < 0)
        speed = -speed;
    if (speed > 4000)
        speed = 4000;
    heading = *(const s16 *)(vehicle + 0x0E);
    look_pitch = *(const s16 *)(record + 0x22);
    look_yaw = *(const s16 *)(record + 0x24);
    if (mode == 4) {
        diff = heading * FRACTION - yaw;
        while (diff >= 32768 * FRACTION)
            diff -= 65536 * FRACTION;
        while (diff < -32768 * FRACTION)
            diff += 65536 * FRACTION;
        diff = diff >= 16384 * FRACTION ? 32767 * FRACTION - diff
             : diff < -16384 * FRACTION ? -32768 * FRACTION - diff : diff;
        yaw += diff / 4 * speed / 4000;
    }
    fine_pitch = clamp_pitch(to_angle(pitch) - look_pitch);
    fine_yaw = to_angle(yaw - look_yaw * FRACTION);
    /* only replace the game's values when they're close to ours */
    d = (s16)(u16)(fine_pitch - angles[0]);
    if (d > 96 || d < -96)
        return;
    d = (s16)(u16)(fine_yaw - angles[1]);
    if (d > 96 || d < -96)
        return;
    angles[0] = (s16)fine_pitch;
    angles[1] = (s16)fine_yaw;
}
